/**
 * The model's numbers reach the mod: balance.json (generated by tools/gem-balance.py) loads, a few known values match,
 * and the model's own example builds (armor and weapon, best build included) come out the same when built from real
 * items through the mod's stacking code.
 */
public class BalanceGameTest {
	private static final String[] PIECES = {"helmet", "chestplate", "leggings", "boots"};

	// Core test: registered by InfusedGemsCoreGameTest (test-lite, specs/quality.md).
	public void balanceJsonLoadsWithKnownValues(GameTestHelper helper) {
		Balance b = Balance.get();
		close(b.cap, 0.90, 1e-9, helper, "cap (owner, question 1)");
		close(b.stackR, 0.85, 1e-9, helper, "stack_r");
		check(helper, b.armorSlots == 3 && b.weaponSlots == 2, "slots 3/2");
		close(b.infusion(1).factor(), 0.40, 1e-9, helper, "Infusion I (owner: wider ladder)");
		close(b.infusion(6).factor(), 1.00, 1e-9, helper, "Infusion VI");
		check(helper, b.infusion(6).item().equals("minecraft:nether_star") && b.infusion(5).item().equals("minecraft:prismarine_shard"), "base gems");
		close(b.armorMaterials.get("netherite"), 1.0, 1e-9, helper, "netherite");
		close(b.armorMaterials.get("leather"), 0.75, 1e-9, helper, "leather");
		close(b.armorMaterials.get("gold"), 0.93, 1e-9, helper, "gold armor: diamond-level magic bonus (owner, question 2)");
		close(b.weaponMaterials.get("gold"), 0.93, 1e-9, helper, "gold weapons: diamond-level magic bonus (owner, question 2)");
		check(helper, !b.armorMaterials.containsKey("turtle"), "the turtle helmet takes no gems (owner, question 3)");
		close(b.effect("resistance").wornNumber("damage_reduction", 0), 0.4, 1e-9, helper, "Resistance 1.0 = Resistance II (owner, question 4)");
		check(helper, b.effect("turtle_master").parts().size() == 2, "Turtle Master gem has two parts (owner, question 5)");
		close(b.run.get(2), 0.90, 1e-9, helper, "run of 2");
		close(b.weaponMaterials.get("bow"), 0.93, 1e-9, helper, "bow");
		check(helper, b.formMaxTier.get("normal") == 1 && b.formMaxTier.get("splash") == 2 && b.formMaxTier.get("lingering") == 3, "form caps");
		close(b.effect("speed").variantFactor("strong"), 1.0, 1e-9, helper, "strong swiftness");
		close(b.effect("speed").wornAttributes().getFirst().amount(), 0.4, 1e-9, helper, "speed attribute");
		close(b.drawbackTotal(1), 0.10, 1e-9, helper, "one drawback");
		JsonObject checks = b.raw.getAsJsonObject("checks");
		List<JsonElement> totals = checks.getAsJsonArray("drawback_totals").asList();
		for (int n = 0; n < totals.size(); n++) {
			close(b.drawbackTotal(n), totals.get(n).getAsDouble(), 1e-6, helper, n + " drawbacks");
		}
		checks.getAsJsonObject("heal_fraction").entrySet().forEach(e ->
				close(b.healFraction(Double.parseDouble(e.getKey())), e.getValue().getAsDouble(), 1e-6, helper, "heal at " + e.getKey()));
		helper.succeed();
	}

	@GameTest
	public void modelBuildsMatchFromRealItems(GameTestHelper helper) {
		Balance b = Balance.get();
		for (JsonElement el : b.raw.getAsJsonObject("checks").getAsJsonArray("armor_builds")) {
			JsonObject build = el.getAsJsonObject();
			Gem gem = GemKit.modelGem(build.get("effect").getAsString(), build.get("variant").getAsString(),
					build.get("base").getAsString(), build.get("grade").getAsString());
			ItemStack[] pieces = new ItemStack[4];
			for (int i = 0; i < 4; i++) {
				JsonElement m = build.getAsJsonArray("layout").get(i);
				int n = build.getAsJsonArray("gems").get(i).getAsInt();
				if (m.isJsonNull()) {
					pieces[i] = ItemStack.EMPTY;
					continue;
				}
				Gem[] gems = new Gem[n];
				java.util.Arrays.fill(gems, gem);
				pieces[i] = GemKit.socketed(armor(m.getAsString(), PIECES[i]), gems);
			}
			double total = GemTotals.ofArmor(pieces).totals().getOrDefault(build.get("effect").getAsString(), 0.0);
			close(total, build.get("total").getAsDouble(), 1e-5, helper, "armor build " + build.get("name").getAsString());
		}
		for (JsonElement el : b.raw.getAsJsonObject("checks").getAsJsonArray("weapon_builds")) {
			JsonObject build = el.getAsJsonObject();
			Gem gem = GemKit.modelGem(build.get("effect").getAsString(), build.get("variant").getAsString(),
					build.get("base").getAsString(), build.get("grade").getAsString());
			List<Gem> gems = new ArrayList<>();
			for (int i = 0; i < build.get("gems").getAsInt(); i++) {
				gems.add(gem);
			}
			ItemStack weapon = GemKit.socketed(weapon(build.get("weapon").getAsString()), gems.toArray(Gem[]::new));
			double total = GemTotals.ofWeapon(weapon).totals().getOrDefault(build.get("effect").getAsString(), 0.0);
			close(total, build.get("total").getAsDouble(), 1e-5, helper, "weapon build " + build.get("name").getAsString());
		}
		helper.succeed();
	}

	/** Every gem has a worn form and a hit form in the mod, with no "later version" gaps (GemsEverywhereGameTest runs them). */
	@GameTest
	public void everyGemHasAWornAndAHitForm(GameTestHelper helper) {
		Balance b = Balance.get();
		check(helper, b.gemEffects.size() == 39, "gem effects: " + b.gemEffects.size());
		for (String key : b.gemEffects) {
			Balance.EffectData e = b.effect(key);
			check(helper, e.worn() != null, key + " has no worn form in balance.json");
			check(helper, !GemDescribe.worn(key, 0.5).matches("[0-9]+%"), key + " has no worn description");
			boolean hitForm = switch (e.hitKind()) {
				case "instant", "action" -> true;
				case "onoff" -> ModEffects.vanilla(key) != null;
				default -> ModEffects.gem(key) != null;
			};
			check(helper, hitForm, key + " has no hit form");
		}
		helper.succeed();
	}

	static Item armor(String material, String piece) {
		String prefix = material.equals("gold") ? "golden" : material;
		return BuiltInRegistries.ITEM.getValue(Identifier.withDefaultNamespace(prefix + "_" + piece));
	}

	static Item weapon(String material) {
		return switch (material) {
			case "bow", "crossbow", "trident", "mace" -> BuiltInRegistries.ITEM.getValue(Identifier.withDefaultNamespace(material));
			case "wood" -> BuiltInRegistries.ITEM.getValue(Identifier.withDefaultNamespace("wooden_sword"));
			case "gold" -> BuiltInRegistries.ITEM.getValue(Identifier.withDefaultNamespace("golden_sword"));
			default -> BuiltInRegistries.ITEM.getValue(Identifier.withDefaultNamespace(material + "_sword"));
		};
	}
}
