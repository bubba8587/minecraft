/**
 * Brewing (data recipes generated by tools/gem-balance.py): potion in each form + base gem gives the right Infused Gem;
 * item sources (golden apple, wither rose) work in the bottle slot; nothing raises an Infused Gem's form afterwards
 * (owner: potion -> gem, no other pathway); a real brewing stand accepts these inputs and brews one. Every brewable
 * effect and variant in balance.json has its recipe; suspicious stews are told apart by their stew effect.
 */
public class BrewingGameTest {
	private static ItemStack brew(GameTestHelper helper, ItemStack input, ItemStack reagent) {
		Optional<RecipeHolder<BrewingRecipe>> recipe = helper.getLevel().recipeAccess()
				.getRecipeFor(RecipeType.BREWING, new BrewingInput(input, reagent), helper.getLevel());
		return recipe.map(r -> r.value().assemble(new BrewingInput(input, reagent))).orElse(ItemStack.EMPTY);
	}

	private static ItemStack potion(net.minecraft.world.item.Item container, Holder<Potion> potion) {
		return PotionContents.createItemStack(container, potion);
	}

	private static void expect(GameTestHelper helper, ItemStack out, String effect, String variant, GemForm form, int infusion) {
		InfusedGem gem = out.get(ModComponents.INFUSED_GEM);
		check(helper, out.is(ModItems.INFUSED_GEM) && gem != null, "no Infused Gem from the brew: " + out);
		check(helper, gem.key().equals(effect) && gem.variant().equals(variant) && gem.form() == form && gem.infusion() == infusion,
				"wrong Infused Gem " + gem + ", expected " + effect + " " + variant + " " + form + " " + infusion);
	}

	@GameTest
	public void potionsAndBaseGemsBrewInfusedGems(GameTestHelper helper) {
		expect(helper, brew(helper, potion(Items.POTION, Potions.SWIFTNESS), new ItemStack(Items.AMETHYST_SHARD)), "speed", "normal", GemForm.NORMAL, 1);
		expect(helper, brew(helper, potion(Items.SPLASH_POTION, Potions.STRONG_STRENGTH), new ItemStack(Items.ENDER_PEARL)), "strength", "strong", GemForm.SPLASH, 3);
		expect(helper, brew(helper, potion(Items.LINGERING_POTION, Potions.LONG_FIRE_RESISTANCE), new ItemStack(Items.NETHER_STAR)), "fire_resistance", "long", GemForm.LINGERING, 6);
		expect(helper, brew(helper, potion(Items.LINGERING_POTION, Potions.STRONG_TURTLE_MASTER), new ItemStack(Items.PRISMARINE_SHARD)), "turtle_master", "strong", GemForm.LINGERING, 5);
		expect(helper, brew(helper, potion(Items.POTION, Potions.STRONG_HARMING), new ItemStack(Items.DIAMOND)), "instant_damage", "strong", GemForm.NORMAL, 4);
		expect(helper, brew(helper, potion(Items.SPLASH_POTION, Potions.POISON), new ItemStack(Items.QUARTZ)), "poison", "normal", GemForm.SPLASH, 2);
		// Items that carry an effect, in the bottle slot.
		expect(helper, brew(helper, new ItemStack(Items.GOLDEN_APPLE), new ItemStack(Items.DIAMOND)), "absorption", "normal", GemForm.ITEM, 4);
		expect(helper, brew(helper, new ItemStack(Items.ENCHANTED_GOLDEN_APPLE), new ItemStack(Items.NETHER_STAR)), "absorption", "strong", GemForm.ITEM, 6);
		expect(helper, brew(helper, new ItemStack(Items.WITHER_ROSE), new ItemStack(Items.AMETHYST_SHARD)), "wither", "normal", GemForm.ITEM, 1);
		// Not gems: an awkward potion, or a base that is no base gem.
		check(helper, !brew(helper, potion(Items.POTION, Potions.AWKWARD), new ItemStack(Items.DIAMOND)).is(ModItems.INFUSED_GEM), "awkward potion made a gem");
		check(helper, !brew(helper, potion(Items.POTION, Potions.SWIFTNESS), new ItemStack(Items.EMERALD)).is(ModItems.INFUSED_GEM), "emerald made a gem");
		// Vanilla brewing still works.
		check(helper, brew(helper, potion(Items.POTION, Potions.AWKWARD), new ItemStack(Items.SUGAR)).is(Items.POTION), "vanilla brewing broke");
		helper.succeed();
	}

	/** A suspicious stew made from this flower, exactly as crafting makes it. */
	static ItemStack stew(ItemLike flower) {
		ItemStack stack = new ItemStack(Items.SUSPICIOUS_STEW);
		stack.set(DataComponents.SUSPICIOUS_STEW_EFFECTS, SuspiciousEffectHolder.tryGet(flower).getSuspiciousEffects());
		return stack;
	}

	/** Every brewable effect and variant from the model: its potion in all three forms, or its source item, with every base gem. */
	@GameTest
	public void everyBrewableSourceBrews(GameTestHelper helper) {
		Balance b = Balance.get();
		int n = 0;
		for (String key : b.brewable) {
			for (Balance.Variant v : b.effect(key).variants().values()) {
				if (key.equals("saturation") || key.equals("blindness")) {
					continue; // stews: below
				}
				for (Balance.Infusion inf : b.infusions) {
					ItemStack reagent = new ItemStack(BuiltInRegistries.ITEM.getValue(Identifier.parse(inf.item())));
					if (v.potion() != null) {
						Holder<Potion> potion = BuiltInRegistries.POTION.get(Identifier.parse(v.potion())).orElseThrow();
						for (GemForm form : new GemForm[] {GemForm.NORMAL, GemForm.SPLASH, GemForm.LINGERING}) {
							net.minecraft.world.item.Item container = form == GemForm.NORMAL ? Items.POTION : form == GemForm.SPLASH ? Items.SPLASH_POTION : Items.LINGERING_POTION;
							expect(helper, brew(helper, potion(container, potion), reagent), key, v.name(), form, inf.level());
							n++;
						}
					} else {
						ItemStack input = new ItemStack(BuiltInRegistries.ITEM.getValue(Identifier.parse(v.item())));
						expect(helper, brew(helper, input, reagent), key, v.name(), GemForm.ITEM, inf.level());
						n++;
					}
				}
			}
		}
		// The ones this version added, by name, so a model change can't silently drop them.
		for (String key : new String[] {"invisibility", "luck", "wind_charged", "weaving", "oozing", "infested", "glowing", "levitation",
				"darkness", "conduit_power", "dolphins_grace", "hunger", "nausea", "saturation", "blindness"}) {
			check(helper, b.brewable.contains(key), key + " is not brewable");
		}
		expect(helper, brew(helper, potion(Items.LINGERING_POTION, Potions.LONG_INVISIBILITY), new ItemStack(Items.NETHER_STAR)), "invisibility", "long", GemForm.LINGERING, 6);
		expect(helper, brew(helper, potion(Items.SPLASH_POTION, Potions.INFESTED), new ItemStack(Items.QUARTZ)), "infested", "normal", GemForm.SPLASH, 2);
		expect(helper, brew(helper, new ItemStack(Items.HEART_OF_THE_SEA), new ItemStack(Items.PRISMARINE_SHARD)), "conduit_power", "normal", GemForm.ITEM, 5);
		check(helper, n > 600, "only " + n + " recipes checked");
		helper.succeed();
	}

	/** Stews by their stew effect (owner): dandelion, golden dandelion, blue orchid give Saturation; azure bluet, open eyeblossom Blindness. */
	@GameTest
	public void suspiciousStewsBrewByTheirEffect(GameTestHelper helper) {
		for (ItemLike flower : new ItemLike[] {Items.DANDELION, Items.GOLDEN_DANDELION, Items.BLUE_ORCHID}) {
			expect(helper, brew(helper, stew(flower), new ItemStack(Items.ENDER_PEARL)), "saturation", "normal", GemForm.ITEM, 3);
		}
		for (ItemLike flower : new ItemLike[] {Items.AZURE_BLUET, Items.OPEN_EYEBLOSSOM}) {
			expect(helper, brew(helper, stew(flower), new ItemStack(Items.AMETHYST_SHARD)), "blindness", "normal", GemForm.ITEM, 1);
		}
		// Other stews, and a stew with no effect, make nothing.
		check(helper, brew(helper, stew(Items.POPPY), new ItemStack(Items.DIAMOND)).isEmpty(), "a poppy stew made a gem");
		check(helper, brew(helper, stew(Items.CLOSED_EYEBLOSSOM), new ItemStack(Items.DIAMOND)).isEmpty(), "a closed eyeblossom stew made a gem");
		check(helper, brew(helper, new ItemStack(Items.SUSPICIOUS_STEW), new ItemStack(Items.DIAMOND)).isEmpty(), "a plain stew made a gem");
		helper.succeed();
	}

	@GameTest
	public void nothingRaisesAnInfusedGemsForm(GameTestHelper helper) {
		ItemStack normal = brew(helper, new ItemStack(Items.GOLDEN_APPLE), new ItemStack(Items.QUARTZ));
		expect(helper, normal, "absorption", "normal", GemForm.ITEM, 2);
		check(helper, brew(helper, normal, new ItemStack(Items.GUNPOWDER)).isEmpty(), "gunpowder raised an Infused Gem");
		check(helper, brew(helper, normal, new ItemStack(Items.DRAGON_BREATH)).isEmpty(), "dragon's breath raised an Infused Gem");
		helper.succeed();
	}

	/** The 26.3 bottle slot takes any item a brewing recipe names as input (PotionIngredient.isPotionInput). */
	@GameTest(maxTicks = 500)
	public void brewingStandAcceptsAndBrews(GameTestHelper helper) {
		BlockPos pos = new BlockPos(1, 1, 1);
		helper.setBlock(pos, Blocks.BREWING_STAND);
		BrewingStandBlockEntity stand = helper.getBlockEntity(pos, BrewingStandBlockEntity.class);
		var access = helper.getLevel().recipeAccess();
		check(helper, PotionIngredient.isPotionInput(new ItemStack(Items.GOLDEN_APPLE), access), "bottle slot refuses a golden apple");
		check(helper, !PotionIngredient.isPotionInput(new ItemStack(ModItems.INFUSED_GEM), access), "bottle slot takes an Infused Gem (nothing brews from one)");
		check(helper, stand.canPlaceItem(0, new ItemStack(Items.WITHER_ROSE)), "stand refuses a wither rose in a bottle slot");
		check(helper, stand.canPlaceItem(1, new ItemStack(Items.ECHO_SHARD)), "stand refuses an echo shard in a bottle slot");
		check(helper, stand.canPlaceItem(2, stew(Items.AZURE_BLUET)), "stand refuses a suspicious stew in a bottle slot");
		for (net.minecraft.world.item.Item item : new net.minecraft.world.item.Item[] {Items.GLOWSTONE_DUST, Items.SHULKER_SHELL, Items.HEART_OF_THE_SEA,
				Items.NAUTILUS_SHELL, Items.ROTTEN_FLESH, Items.PUFFERFISH}) {
			check(helper, PotionIngredient.isPotionInput(new ItemStack(item), access), "bottle slot refuses " + item);
		}
		check(helper, stand.canPlaceItem(3, new ItemStack(Items.NETHER_STAR)), "stand refuses a nether star as reagent");
		check(helper, stand.canPlaceItem(3, new ItemStack(Items.AMETHYST_SHARD)), "stand refuses an amethyst shard as reagent");
		stand.setItem(0, potion(Items.LINGERING_POTION, Potions.STRONG_SWIFTNESS));
		stand.setItem(1, new ItemStack(Items.ECHO_SHARD));
		stand.setItem(2, stew(Items.DANDELION));
		stand.setItem(3, new ItemStack(Items.NETHER_STAR));
		stand.setItem(4, new ItemStack(Items.BLAZE_POWDER));
		helper.succeedWhen(() -> {
			InfusedGem a = stand.getItem(0).get(ModComponents.INFUSED_GEM);
			InfusedGem b = stand.getItem(1).get(ModComponents.INFUSED_GEM);
			InfusedGem c = stand.getItem(2).get(ModComponents.INFUSED_GEM);
			if (a == null || b == null || c == null) {
				helper.fail("not brewed yet");
			}
			check(helper, a.key().equals("speed") && a.form() == GemForm.LINGERING && a.infusion() == 6, "stand brewed " + a);
			check(helper, b.key().equals("darkness") && b.form() == GemForm.ITEM && b.infusion() == 6, "stand brewed " + b);
			check(helper, c.key().equals("saturation") && c.form() == GemForm.ITEM && c.infusion() == 6, "stand brewed " + c);
			check(helper, stand.getItem(3).isEmpty(), "nether star not used up");
		});
	}
}
